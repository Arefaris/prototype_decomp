"""Summarise what the engine DLL tells about its own source: the original source tree and the classes per namespace.

    python tools/survey.py [--version PROTOPC_2025]      (run tools/rtti.py first)

Writes docs/original_tree.md. Source paths come from assert/__FILE__ strings ("..\..\..\code\core\src\...cpp"),
classes from config/<VERSION>/classes.tsv.
"""

import argparse
import collections
import csv
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]


def sourcePaths(data):
	paths = set()
	for m in re.finditer(rb"(?:\.\.[\\])+[A-Za-z0-9_\\\-]+\.(?:cpp|c|h|hpp|inl)\0", data):
		path = m.group()[:-1].decode("latin-1")
		paths.add(re.sub(r"^(\.\.[\\])+", "", path).replace("\\", "/"))
	return sorted(paths)


def outerNamespace(name):
	if name.startswith("`"):
		return "(function-local)"
	# "proto::fight::Foo<bar::Baz>" -> "proto"; global names -> "(global)"
	head = re.split(r"[<(]", name, 1)[0]
	parts = head.split("::")
	return parts[0] if len(parts) > 1 else "(global)"


def main():
	parser = argparse.ArgumentParser()
	parser.add_argument("--version", default="PROTOPC_2025")
	args = parser.parse_args()
	data = (ROOT / "orig" / args.version / "prototypeenginef.dll").read_bytes()
	paths = sourcePaths(data)
	with open(ROOT / "config" / args.version / "classes.tsv", encoding="utf-8") as f:
		rows = list(csv.DictReader(f, delimiter="\t"))
	plain = collections.Counter()
	templates = collections.Counter()
	for row in rows:
		ns = outerNamespace(row["class"])
		(templates if "<" in row["class"] else plain)[ns] += 1

	lines = ["# The original source tree", "",
		f"Generated by `tools/survey.py` from `{args.version}`. Do not edit by hand.", "",
		"## Source files named by the binary", "",
		f"{len(paths)} paths survive in assert / `__FILE__` strings. They are relative to the build directory",
		"`c:/workspace/outrun/proto/prototype/playable/win32/` (from the PDB path), so `code/` is",
		"`c:/workspace/outrun/proto/prototype/code/` and `atg/` is `c:/workspace/outrun/proto/atg/` or above.", "",
		"```"]
	lines += paths
	lines += ["```", "", "## Modules", "",
		"Directories under `code/` and the namespaces of the classes found in the RTTI:", "",
		"| Namespace | Classes | Template instances | Directory |", "|---|---:|---:|---|"]
	directories = {p.split("/")[1] for p in paths if p.startswith("code/")}
	for ns in sorted(set(plain) | set(templates), key=lambda n: -(plain[n] + templates[n])):
		directory = f"`code/{ns}`" if ns in directories else ""
		lines.append(f"| `{ns}` | {plain[ns]} | {templates[ns]} | {directory} |")
	lines += ["", f"Total: {sum(plain.values())} classes and {sum(templates.values())} template instances with RTTI "
		"(`config/" + args.version + "/classes.tsv`; vftables in `rtti.tsv`).", ""]
	(ROOT / "docs" / "original_tree.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")
	print(f"{len(paths)} source paths, {len(rows)} classes")


if __name__ == "__main__":
	main()
