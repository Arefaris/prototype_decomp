"""Progress of the decompilation over the whole engine DLL.

    python tools/progress.py [--version PROTOPC_2025] [--markdown docs/progress.md]

Numerator: functions objdiff reports as 100 % matching (build/<VERSION>/report.json, `ninja report`), mapped to
addresses through symbols.txt. Denominator: every function of the original (config/<VERSION>/functions.tsv), by
count and by bytes.
"""

import argparse
import collections
import csv
import datetime
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools" / "delink"))
import relink  # noqa: E402


def main():
	parser = argparse.ArgumentParser()
	parser.add_argument("--version", default="PROTOPC_2025")
	parser.add_argument("--markdown")
	args = parser.parse_args()
	config = ROOT / "config" / args.version
	sizes = {}
	with open(config / "functions.tsv", encoding="utf-8") as f:
		for row in csv.DictReader(f, delimiter="\t"):
			sizes[int(row["address"], 16)] = int(row["size"])
	symbols = relink.loadSymbols(args.version)
	report = json.loads((ROOT / "build" / args.version / "report.json").read_text(encoding="utf-8"))
	matched = {}
	perModule = collections.defaultdict(lambda: [0, 0])
	for unit in report["units"]:
		module = unit["name"].split("/")[1]
		for function in unit.get("functions", []):
			address = symbols.get(function["name"])
			if address is None or function.get("fuzzy_match_percent", 0) < 100.0:
				continue
			size = sizes.get(address, int(function["size"]))
			matched[address] = size
			perModule[module][0] += 1
			perModule[module][1] += size
	totalBytes = sum(sizes.values())
	doneBytes = sum(matched.values())
	lines = [
		f"Functions: {len(matched)} / {len(sizes)} ({100.0 * len(matched) / len(sizes):.3f} %)",
		f"Code:      {doneBytes} / {totalBytes} bytes ({100.0 * doneBytes / totalBytes:.3f} %)",
	]
	for module, (count, size) in sorted(perModule.items()):
		lines.append(f"  {module:14s} {count:6d} functions {size:9d} bytes")
	print("\n".join(lines))
	if args.markdown:
		table = ["| Module | Functions | Bytes |", "|---|---:|---:|"]
		table += [f"| `{m}` | {c} | {s} |" for m, (c, s) in sorted(perModule.items())]
		text = [
			"# Progress", "",
			f"Generated by `tools/progress.py` on {datetime.date.today().isoformat()} for `{args.version}`.", "",
			"| | Matched | Total | |", "|---|---:|---:|---:|",
			f"| Functions | {len(matched)} | {len(sizes)} | {100.0 * len(matched) / len(sizes):.3f} % |",
			f"| Code bytes | {doneBytes} | {totalBytes} | {100.0 * doneBytes / totalBytes:.3f} % |", "",
			"Matched means byte-identical to the original with relocations as wildcards (objdiff). The total counts every",
			"function of the original except the incremental link thunks (`config/" + args.version + "/functions.tsv`).", "",
		] + table + [""]
		pathlib.Path(args.markdown).write_text("\n".join(text), encoding="utf-8", newline="\n")


if __name__ == "__main__":
	main()
