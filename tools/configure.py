"""Generate build.ninja, objdiff.json and build/<VERSION>/units.json from the sources.

    python tools/configure.py [--version PROTOPC_2025]
    ninja                 # compile src/, cut the original's target objects (what objdiff needs)
    ninja check           # objcmp every annotated function
    ninja dll             # relink the hybrid DLL and verify it
    ninja report          # objdiff progress report -> build/<VERSION>/report.json
    ninja progress        # docs/progress.md over the whole DLL

A unit is one source file under src/ (one original translation unit); its functions are the
"// FUNCTION: ENGINE 0xADDRESS" annotations in it. Rerun configure.py after adding a source file or an annotation
(ninja does it by itself when a source changes, since build.ninja depends on them).
"""

import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import build  # noqa: E402  (compiler options)

OBJDIFF = r"D:\tools\objdiff\objdiff-cli.exe"


def ninjaPath(path):
	return str(path).replace("\\", "/").replace(":", "$:").replace(" ", "$ ")


def scanUnits():
	units = []
	for source in sorted((ROOT / "src").rglob("*.cpp")):
		name = source.relative_to(ROOT / "src").with_suffix("").as_posix()
		# NONMATCHING functions stay in the target (objdiff counts them as not done) but are not compiled
		functions = [address for address, _ in build.annotations(source.read_text(encoding="utf-8"))]
		units.append({"name": name, "source": source.relative_to(ROOT).as_posix(), "functions": functions})
	return units


def main():
	parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
	parser.add_argument("--version", default="PROTOPC_2025")
	args = parser.parse_args()
	version = args.version
	buildDir = ROOT / "build" / version
	buildDir.mkdir(parents=True, exist_ok=True)
	units = scanUnits()
	(buildDir / "units.json").write_text(json.dumps({"units": units}, indent=1), encoding="utf-8")

	objdiff = {
		"$schema": "https://raw.githubusercontent.com/encounter/objdiff/main/config.schema.json",
		"custom_make": "ninja",
		"build_target": False,
		"build_base": True,
		"watch_patterns": ["*.cpp", "*.h", "*.txt", "*.py"],
		"units": [{
			"name": unit["name"],
			"target_path": f"build/{version}/target/{unit['name']}.obj",
			"base_path": f"build/{version}/obj/{unit['name']}.obj",
			"metadata": {"source_path": unit["source"], "progress_categories": [unit["name"].split("/")[1]]},
		} for unit in units if unit["functions"]],
		# One progress category per module under code/ (math, pure3d, proto, ...)
		"progress_categories": [{"id": c, "name": c} for c in sorted({u["name"].split("/")[1] for u in units})],
	}
	(ROOT / "objdiff.json").write_text(json.dumps(objdiff, indent=2), encoding="utf-8")

	python = ninjaPath(sys.executable)
	cflags = " ".join(build.CFLAGS)
	lines = [
		f"# Generated by tools/configure.py --version {version}; do not edit",
		"ninja_required_version = 1.10",
		f"python = {python}",
		f"cflags = {cflags}",
		"",
		"rule configure",
		f"  command = $python tools/configure.py --version {version}",
		"  generator = 1",
		"  description = configure",
		"rule cc",
		"  command = $python tools/toolchain/cl8.py cl $cflags /showIncludes /Fo$out $in",
		"  deps = msvc",
		"  description = cc $in",
		"rule split",
		f"  command = $python tools/delink/split.py $in --version {version}",
		"  description = split target objects",
		"rule relink",
		f"  command = $python tools/delink/relink.py --version {version} $in",
		"  description = relink prototypeenginef.dll",
		"rule verify",
		f"  command = $python tools/delink/verify.py --version {version} --stamp $out",
		"  description = verify",
		"rule check",
		f"  command = $python tools/build.py --version {version} --no-link --no-compile --stamp $out",
		"  description = objcmp annotated functions",
		"rule report",
		f"  command = {ninjaPath(OBJDIFF)} report generate -o $out",
		"  description = objdiff report",
		"rule progress",
		f"  command = $python tools/progress.py --version {version} --markdown $out --svg docs/progress.svg --readme README.md",
		"  description = progress",
		"",
	]
	sources = [unit["source"] for unit in units]
	lines.append(f"build build.ninja: configure | tools/configure.py {' '.join(sources)}")
	objects, targets = [], []
	for unit in units:
		obj = f"build/{version}/obj/{unit['name']}.obj"
		objects.append(obj)
		lines.append(f"build {obj}: cc {unit['source']}")
		if unit["functions"]:
			targets.append(f"build/{version}/target/{unit['name']}.obj")
	symbols = f"config/{version}/symbols.txt"
	orig = f"orig/{version}/prototypeenginef.dll"
	if targets:
		lines.append(f"build {' '.join(targets)}: split build/{version}/units.json | {symbols} {orig} tools/delink/split.py")
	dll = f"build/{version}/relink/prototypeenginef.dll"
	lines += [
		f"build {dll} build/{version}/relink/relink.json: relink {' '.join(objects)} | {symbols} {orig} tools/delink/relink.py",
		f"build build/{version}/verified.stamp: verify {dll}",
		f"build build/{version}/checked.stamp: check {' '.join(objects)} | {symbols}",
		f"build build/{version}/report.json: report {' '.join(objects + targets)} | objdiff.json",
		f"build dll: phony build/{version}/verified.stamp",
		f"build check: phony build/{version}/checked.stamp",
		f"build report: phony build/{version}/report.json",
		f"build docs/progress.md: progress build/{version}/report.json | config/{version}/functions.tsv",
		"build progress: phony docs/progress.md",
		f"default {' '.join(objects + targets)}",
		"",
	]
	(ROOT / "build.ninja").write_text("\n".join(lines), encoding="utf-8")
	done = sum(len(u["functions"]) for u in units)
	print(f"{len(units)} units, {done} annotated functions -> build.ninja, objdiff.json")


if __name__ == "__main__":
	main()
